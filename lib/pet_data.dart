class PetData {
  final String name;
  final String breed;
  final String imageAsset;
  final String gender;
  final String age;
  final String height;
  final String weight;

  PetData({
    required this.name,
    required this.breed,
    required this.imageAsset,
    required this.gender,
    required this.age,
    required this.height,
    required this.weight,
  });
}